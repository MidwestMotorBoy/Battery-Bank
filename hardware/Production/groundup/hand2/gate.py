"""gate.py port -> hand spec (json on stdout) for the gate drives, switch-node returns, bootstrap and driver-supply
escapes of one charger stage. Coordinates are port 2's; port 1 is the same pattern 23.026 mm to the right."""
import json, sys
port = int(sys.argv[1]); dx = 0.0 if port == 2 else 23.026; P = '/USB Port %d/' % port
S = []
def T(net, layer, w, *pts): S.append({"net": net if net == 'GND' else P + net, "layer": layer, "w": w, "pts": [[round(x + dx, 4), y] for x, y in pts]})
def V(net, x, y): S.append({"net": net if net == 'GND' else P + net, "via": [round(x + dx, 4), y]})
def D(net, what, x, y): S.append({"del": [round(x + dx, 4), y], "net": net if net == 'GND' else P + net, "what": what})
# ---- leg A
T('SW1', 'F', 0.15, (85.565, 108.84), (85.565, 107.6), (85.85, 107.31)); T('SW1', 'F', 0.25, (85.85, 107.31), (85.95, 107.15))
T("SW1", "F", 0.3, (86.1, 106.8), (86.1, 104.0), (85.8, 103.7), (85.8, 101.05))                     # return: C512 -> Q501 source
T('HIDRV1', 'F', 0.15, (86.065, 108.84), (86.065, 107.95)); V('HIDRV1', 86.065, 107.95)
T('HIDRV1', 'In2', 0.3, (86.065, 107.95), (86.065, 103.6), (86.45, 103.215), (87.4, 103.215)); V('HIDRV1', 87.4, 103.215)
T('HIDRV1', 'F', 0.3, (87.4, 103.215), (88.0, 103.21))
T('BTST1', 'F', 0.15, (86.565, 108.84), (86.565, 107.7), (86.9, 107.31)); T('BTST1', 'F', 0.2, (86.9, 107.31), (87.0, 107.15))
V('BTST1', 87.04, 106.3); T('BTST1', 'F', 0.2, (87.04, 106.3), (87.04, 106.8))
V('BTST1', 85.45, 104.71); T('BTST1', 'F', 0.2, (85.45, 104.71), (85.37, 105.35)); T('BTST1', 'B', 0.2, (87.04, 106.3), (85.45, 104.71))
T('LODRV1', 'F', 0.15, (87.065, 108.84), (87.065, 108.0)); V('LODRV1', 87.065, 108.0)
T('LODRV1', 'B', 0.3, (87.065, 108.0), (84.9, 105.835), (84.9, 104.05)); V('LODRV1', 84.9, 104.05); T('LODRV1', 'F', 0.3, (84.9, 104.05), (84.9, 103.3))
T('REGN', 'F', 0.15, (87.565, 108.84), (87.565, 108.35), (87.605, 108.25)); T('REGN', 'F', 0.2, (87.605, 108.25), (87.605, 104.8), (87.95, 104.35), (88.1, 104.2))
T('DRV_SUP', 'F', 0.15, (88.065, 108.84), (88.065, 108.3)); T('DRV_SUP', 'F', 0.25, (88.065, 108.3), (88.065, 107.6))
V('TS', 86.75, 103.95); T('TS', 'F', 0.2, (86.52, 103.29), (86.75, 103.6), (86.75, 103.95))              # thermistor between the FETs
V('DRV_SUP', 86.77, 104.75); T('DRV_SUP', 'F', 0.25, (86.77, 104.75), (86.77, 105.4))                   # bootstrap diode feed
# ---- escapes of charger pins 1 to 3 (I2C clock, data, interrupt)
for net, x, y in (('I2CC_SCL', 85.564, 114.175), ('I2CC_SDA', 86.064, 114.8), ('CHG_INT', 86.564, 114.175)):
    T(net, 'F', 0.15, (x, 113.64), (x, y)); V(net, x, y)
# ---- leg B
T('LODRV2', 'F', 0.15, (89.065, 108.84), (89.065, 108.45), (89.645, 107.87)); T('LODRV2', 'F', 0.2, (89.645, 107.87), (89.645, 104.7))
T('LODRV2', 'F', 0.15, (89.645, 104.7), (89.645, 103.3))
T('BTST2', 'F', 0.15, (89.565, 108.84), (89.565, 108.5), (90.0, 108.065), (90.05, 107.9))
T('BTST2', 'F', 0.2, (90.45, 107.73), (90.57, 107.73), (90.87, 107.43), (90.87, 105.5))
T('HIDRV2', 'F', 0.15, (90.065, 108.84), (90.065, 108.45), (90.24, 108.275), (91.285, 108.275), (91.46, 108.1), (91.46, 103.6), (91.85, 103.21)); T('HIDRV2', 'F', 0.3, (91.85, 103.21), (92.5, 103.21))
T('SW2', 'F', 0.2, (90.71, 109.49), (91.2, 109.49), (91.4, 109.3)); V('SW2', 91.4, 109.3)
T('SW2', 'B', 0.3, (91.4, 109.3), (91.4, 107.2), (90.2, 106.0)); V('SW2', 90.2, 106.0)
T('SW2', 'F', 0.3, (90.26, 106.6), (90.2, 106.0), (90.12, 105.8), (90.12, 101.05))                      # return: C513 -> Q502 source
V('GND', 89.1, 104.67)                                                                                # at the driver-supply capacitor's ground pad
if port == 2:
    D('GND', 'via', 85.975, 114.975)
    D('GND', 'via', 89.825, 104.9745); D('GND', 'F', 89.825, 104.9745)
else:
    D('GND', 'via', 109.712 - dx, 104.484)
    D('GND', 'via', 108.825 - dx, 102.0245); D('GND', 'F', 108.825 - dx, 102.0245)
    V('GND', 87.225, 102.4245); T('GND', 'F', 0.25, (86.524, 102.27), (87.225, 102.4245))
    # port 1 only: the filtered battery-sense line wandered through the leg B drive corridor; redraw it straight
    for x, y in ((115.325, 105.9745), (115.475, 106.3245), (115.125, 106.8745), (114.925, 107.5745), (114.525, 108.2745), (114.375, 108.8245),
                 (115.075, 109.4745), (115.275, 109.6745)):
        D('SRN_F', 'F', x - dx, y)
    T('SRN_F', 'F', 0.2, (92.564, 105.65), (92.3, 105.97), (92.3, 106.2), (91.9, 106.6), (91.9, 109.3), (92.2, 109.6), (92.444, 110.0))
print(json.dumps(S))
